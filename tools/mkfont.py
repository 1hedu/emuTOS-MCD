ORDER = (list("0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZ.-_")
         + ["^", "<", "J2", "x", "[]", "[x]", "AU", "AD", "AL", "AR", "<>"])


def tile(rows):
    """8x8 glyph rows (list of 5-wide bit strings, 7 tall) -> 32-byte tile."""
    out = bytearray(32)
    grid = [[0] * 8 for _ in range(8)]
    for y, r in enumerate(rows):           # 7 rows, top-aligned at y=0..6
        for x, c in enumerate(r):          # 5 wide, offset +1 to center
            if c == "#" or c == "1":
                grid[y][x + 1] = 1
    for y in range(8):
        for xp in range(0, 8, 2):
            hi = grid[y][xp] & 0xF
            lo = grid[y][xp + 1] & 0xF
            out[y * 4 + xp // 2] = (hi << 4) | lo
    return out


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "iofw/osk_font.h"
    tiles = [bytes(32)]                     # glyph 0 = blank
    for name in ORDER:
        tiles.append(tile(G[name]))
    with open(out, "w") as f:
        f.write("/* generated by tools/mkfont.py — do not edit */\n")
        f.write("static const unsigned char osk_font[%d] = {\n" % (len(tiles) * 32))
        for t in tiles:
            f.write("  " + ",".join(str(b) for b in t) + ",\n")
        f.write("};\n")
        f.write("#define OSK_GLYPH_COUNT %d\n" % len(tiles))
    print("%s: %d glyph tiles" % (out, len(tiles)))


if __name__ == "__main__":
    main()
